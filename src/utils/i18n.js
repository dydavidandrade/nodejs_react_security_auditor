let currentLang = 'es';

export function setLang(lang) { currentLang = lang; }

export function t(key, vars = {}) {
  const str = translations[currentLang]?.[key] ?? translations.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

export { translations };
